#!/usr/bin/env python3
"""Regenerate `skills/audit-orchestrator/references/example-report.json`.

The worked example in the documentation is generated, not hand-written, so it
can never drift from what the marketplace actually emits. It runs the real
entrypoint against the deterministic fixture site the test suite uses, then
trims the volatile parts (timestamps, ephemeral ports, timings) and caps the
long arrays so the file stays readable.

    python tools/make_example_report.py
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tests"))
sys.path.insert(0, str(ROOT / "skills" / "audit-orchestrator" / "scripts"))

TARGET = ROOT / "skills" / "audit-orchestrator" / "references" / "example-report.json"
PLACEHOLDER_HOST = "https://example.test"


def stabilise(value, port_pattern):
    """Replace the fixture's ephemeral origin and volatile fields."""
    if isinstance(value, dict):
        return {k: stabilise(v, port_pattern) for k, v in value.items()}
    if isinstance(value, list):
        return [stabilise(v, port_pattern) for v in value]
    if isinstance(value, str):
        return port_pattern.sub(PLACEHOLDER_HOST, value)
    return value


def main() -> int:
    from fixture_server import FixtureSite, Route, RICH_PARAGRAPH, page
    from test_end_to_end import DEFECTIVE_SITE

    with FixtureSite(DEFECTIVE_SITE) as site, tempfile.TemporaryDirectory() as tmp:
        base = site.url.rstrip("/")
        site.routes["/sitemap.xml"] = Route(
            '<?xml version="1.0"?><urlset '
            'xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'
            + "".join("<url><loc>%s%s</loc></url>" % (base, p)
                      for p in ("/", "/about", "/products/planner",
                                "/blog/forecasting", "/contact", "/hidden"))
            + "</urlset>", content_type="application/xml")
        site.routes["/hidden"] = Route(page("Hidden", body=RICH_PARAGRAPH))

        out = Path(tmp) / "report.json"
        completed = subprocess.run(
            [sys.executable,
             str(ROOT / "skills/audit-orchestrator/scripts/run_audit.py"),
             "--url", site.url, "--out", str(out), "--rate", "50", "--quiet"],
            capture_output=True, text=True, timeout=180)
        if completed.returncode != 0:
            sys.stderr.write(completed.stderr)
            return 1
        report = json.loads(out.read_text(encoding="utf-8"))

    report = stabilise(report, re.compile(re.escape(base)))
    report["site"] = "example.test"
    report["audited_url"] = PLACEHOLDER_HOST + "/"
    report["audited_at"] = "2026-09-04T14:32:00Z"
    report["audit_metrics"].update({"duration_ms": 41280,
                                    "phase_ms": {"discovery_ms": 2140, "crawl_ms": 26890,
                                                 "analysis_ms": 39810,
                                                 "compose_ms": 41240}})
    report["engine"]["user_agent"] = (
        "Mozilla/5.0 (compatible; BrandAIReadinessAudit/1.0; "
        "+https://agentskills.io/) read-only-site-auditor")

    # Trim only the repetitive arrays. The findings list is left complete so the
    # example remains a *valid* report - its summary counts must still match.
    for finding in report["findings"]:
        finding["evidence_items"] = finding["evidence_items"][:3]
        finding["affected_urls"] = finding["affected_urls"][:4]
    report["coverage"]["checks"] = report["coverage"]["checks"][:15]
    report["_note"] = (
        "Generated by tools/make_example_report.py against the deterministic test "
        "fixture. Every finding is present; only per-finding evidence_items, "
        "affected_urls and coverage.checks are truncated for readability, so the "
        "document still validates against the required schema.")

    from auditlib import schema
    errors = schema.validate(report)
    if errors:
        sys.stderr.write("refusing to write an invalid example: %s\n" % errors[:3])
        return 1

    TARGET.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n",
                      encoding="utf-8")
    sys.stderr.write("wrote %s (%d KB)\n"
                     % (TARGET.relative_to(ROOT), TARGET.stat().st_size // 1024))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
